import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const directory = mkdtempSync(join(tmpdir(), 'spill-migration-'));
const database = join(directory, 'rehearsal.sqlite');
const execute = source => execFileSync('sqlite3', [database], { input: `PRAGMA foreign_keys=ON;\n${source}`, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }).trim();
const baseline = execFileSync('git', ['show', '274736c:api/schema.sql'], { encoding: 'utf8' });
execute(baseline);
execute(`INSERT INTO discussion_sessions(id,title,topic,public_code,status) VALUES('session-a','Migration fixture','Preserve event data','ABCDEFGH','closed');
INSERT INTO discussion_sessions(id,title,topic,public_code,status) VALUES('session-b','Other fixture','Separate event','BCDEFGHJ','paused');
INSERT INTO submissions(id,session_id,participant_id,nickname,category,content,moderation_status) VALUES('contribution-a','session-a','browser-a','Anonymous','question','Preserve this contribution','approved');
INSERT INTO presentation_state(session_id,current_submission_id) VALUES('session-a','contribution-a');`);
execute(readFileSync('api/migrations/004_platform.sql', 'utf8'));
assert.equal(execute('SELECT version FROM spill_schema_migrations;'), '004_platform');
execute(readFileSync('api/migrations/005_stage.sql', 'utf8'));
assert.equal(execute("SELECT version FROM spill_schema_migrations WHERE version='005_stage';"), '005_stage');
assert.equal(execute('SELECT COUNT(*) FROM discussion_sessions;'), '2');
assert.equal(execute('SELECT content FROM submissions;'), 'Preserve this contribution');
assert.equal(execute('SELECT current_submission_id FROM presentation_state WHERE session_id=\'session-a\';'), 'contribution-a');
assert.equal(execute('SELECT revision FROM submissions;'), '0');
assert.equal(execute('PRAGMA foreign_key_check;'), '');
assert.equal(execute('PRAGMA integrity_check;'), 'ok');
assert.throws(() => execute("INSERT INTO projection_queue VALUES('session-b','contribution-a',0);"));
execute("INSERT INTO platform_state(session_id) VALUES('session-a'); INSERT INTO projection_queue VALUES('session-a','contribution-a',0);");
execute("UPDATE submissions SET moderation_status='hidden' WHERE id='contribution-a';");
assert.equal(execute('SELECT COUNT(*) FROM projection_queue;'), '0');
assert.equal(execute("SELECT current_submission_id IS NULL FROM presentation_state WHERE session_id='session-a';"), '1');
assert.throws(() => execute("UPDATE presentation_state SET current_submission_id='contribution-a' WHERE session_id='session-a';"));
execute("DELETE FROM discussion_sessions WHERE id='session-a';");
assert.equal(execute("SELECT COUNT(*) FROM admin_activity WHERE action='delete_session';"), '1');
console.log(JSON.stringify({ migration: '004_platform', preservedSessions: 2, preservedContributions: 1, crossSessionQueueRejected: true, hiddenProjectionRejected: true, deletionActivityRetained: true, integrity: 'ok', database }));
