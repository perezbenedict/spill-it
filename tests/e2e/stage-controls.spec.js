import { expect, test } from '@playwright/test';
import { E2E, requireLocalMutationTarget } from '../helpers/e2e-env.js';

test('stage controls persist atmosphere, chapter, prompt and timed reflection', async ({ page, context }) => {
  test.setTimeout(90000);
  requireLocalMutationTarget(test);
  const worker = process.env.SPILL_E2E_WORKER_URL;
  const headers = { Authorization: `Bearer ${process.env.SPILL_E2E_API_SECRET}`, 'Content-Type': 'application/json' };
  const login = await fetch(`${worker}/admin/auth/login`, { method: 'POST', headers, body: JSON.stringify({ password: E2E.adminPassword }) });
  expect(login.status).toBe(200);
  const token = (await login.json()).token;
  const state = async () => (await fetch(`${worker}/admin/sessions/${E2E.adminSessionId}/platform`, { headers: { ...headers, 'X-Admin-Token': token } })).json();
  await context.addCookies([{ name: 'spill_admin_session', value: token, url: E2E.baseURL, httpOnly: true, sameSite: 'Lax' }]);
  await page.goto(`/admin/sessions/${E2E.adminSessionId}/live`);
  await page.getByText('Stage direction · atmosphere, chapters, prompts & reflection', { exact: true }).click();
  await page.getByLabel('Preview atmosphere').selectOption('electric');
  await page.getByRole('button', { name: 'Apply atmosphere', exact: true }).click();
  await expect.poll(async () => (await state()).stage.atmosphere).toBe('electric');
  await page.getByLabel('Chapter title').fill('Opening perspectives');
  await page.getByRole('button', { name: 'Add chapter', exact: true }).click();
  await page.getByRole('button', { name: 'Activate chapter', exact: true }).click();
  await expect.poll(async () => (await state()).stage.activeChapterId).toBeTruthy();
  await page.getByLabel('New prompt', { exact: true }).fill('What changed your perspective?');
  await page.getByRole('button', { name: 'Save prompt', exact: true }).click();
  await page.getByRole('button', { name: 'Project prompt', exact: true }).click();
  const room = await context.newPage();
  await room.goto(`/room/${E2E.liveCode}`);
  await expect(room.locator('[data-stage-overlay="prompt"] h1')).toHaveText('What changed your perspective?');
  await expect(room.locator('[data-atmosphere]')).toHaveAttribute('data-atmosphere', 'electric');
  await expect(room.locator('[data-active-chapter]')).toHaveText('Opening perspectives');
  await page.getByRole('button', { name: 'Clear spotlight or reflection', exact: true }).click();
  await expect(room.locator('[data-stage-overlay]')).not.toBeVisible();
  await page.getByLabel('Reflection message', { exact: true }).fill('Consider what comes next.');
  await page.getByLabel('Duration in seconds (optional)', { exact: true }).fill('8');
  await page.getByRole('button', { name: 'Begin reflection', exact: true }).click();
  await expect(room.locator('[data-stage-overlay="reflection"] h1')).toHaveText('Consider what comes next.');
  await expect(room.getByLabel('Reflection time remaining')).toBeVisible();
  await expect(room.locator('[data-stage-overlay]')).not.toBeVisible({ timeout: 15000 });
  await expect(room.locator('[data-current-contribution-id]')).toHaveAttribute('data-current-contribution-id', E2E.projectionIds[0]);
  await room.close();
});
